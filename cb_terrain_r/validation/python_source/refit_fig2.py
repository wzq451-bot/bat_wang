"""Fit the supplied 3360 observed steps ONLY after all original controls are supplied.

Usage: python scripts/refit_fig2.py --candidates input/full_candidates.csv
No synthetic or display-only candidates are generated by this script.
"""
from pathlib import Path
import argparse,json,hashlib,sys
import numpy as np
import pandas as pd
from scipy.stats import norm,t
from conditional_logit import fit,coefficient_rows
ROOT=Path(__file__).resolve().parents[1]

def validate_candidates(c,m):
 if 'used' in c:
  if not c.used.isin([0,1]).all():raise ValueError('used must be 0 for alternatives and 1 for observed endpoints')
  c=c.loc[c.used.eq(0)].copy()
 for old,new in [('end_lon','lon'),('end_lat','lat'),('end_elev','elev'),('end_tpi','tpi'),('end_tri','tri')]:
  if new not in c and old in c:c=c.rename(columns={old:new})
 required=['step_id','elev','tpi','tri']
 missing=[n for n in required if n not in c]
 if missing:raise ValueError('Missing candidate columns: '+', '.join(missing))
 if not np.isfinite(c[required].to_numpy(dtype=float)).all():raise ValueError('Nonfinite candidate identifiers, coordinates or terrain values')
 ids=set(m.step_id);present=set(c.step_id)
 if ids!=present:raise ValueError(f'Candidate coverage incomplete: {len(ids-present)} missing steps, {len(present-ids)} unexpected steps. Expected all {len(ids)} steps.')
 counts=c.groupby('step_id').size()
 if not counts.eq(40).all():raise ValueError('This specification requires the original 40 controls per step. Do not pad or duplicate rows to pass this check.')
 if 'candidate_id' in c and c.duplicated(['step_id','candidate_id']).any():raise ValueError('Duplicated candidate_id within step')
 if {'lon','lat'}.issubset(c.columns):
  if not c.lon.between(-180,180).all() or not c.lat.between(-90,90).all():raise ValueError('Candidate coordinates must be longitude/latitude in degrees')
 else:
  c['lon']=np.nan;c['lat']=np.nan  # Coordinates absent: never fabricate map positions.
 return c.sort_values(['step_id','candidate_id'] if 'candidate_id' in c else ['step_id'],kind='stable').copy()

def run(candidate_path):
 m=pd.read_csv(ROOT/'results/master_validated.csv').sort_values('step_id').reset_index(drop=True)
 c=validate_candidates(pd.read_csv(candidate_path),m)
 if 'candidate_id' not in c:c['candidate_id']=c.groupby('step_id').cumcount()+1
 c['choice_index']=c.groupby('step_id').cumcount()+1;c['used']=0
 obs=pd.DataFrame({'step_id':m.step_id,'candidate_id':0,'choice_index':0,'used':1,'lon':m['经度'],'lat':m['纬度'],'elev':m.end_elev,'tpi':m.end_tpi,'tri':m.end_tri})
 choices=pd.concat([obs,c[['step_id','candidate_id','choice_index','used','lon','lat','elev','tpi','tri']]],ignore_index=True)
 choices=choices.merge(m[['step_id','ind','start_agl','dt_min']],on='step_id',validate='many_to_one').sort_values(['step_id','choice_index']).reset_index(drop=True)
 assert np.array_equal(choices.groupby('step_id').used.sum().to_numpy(),np.ones(len(m)))
 out=ROOT/'results/refit';out.mkdir(exist_ok=True)
 choices.to_csv(out/'matched_choices.csv.gz',index=False,compression='gzip')
 names=['tpi','elev','tri','start_agl'];scaling={}
 for n in names:
  mu=float(choices[n].mean());sd=float(choices[n].std(ddof=1))
  if sd<=0:raise ValueError(f'Constant predictor {n}')
  scaling[n]={'mean':mu,'sd':sd};choices[n+'_z']=(choices[n]-mu)/sd
 X3=choices[['tpi_z','elev_z','tri_z']].to_numpy().reshape(len(m),41,3)
 az=choices.start_agl_z.to_numpy().reshape(len(m),41)
 X4=np.concatenate([X3,(az*X3[:,:,0])[:,:,None]],axis=2)
 bats=m.ind.to_numpy();terms3=['tpi_z','elev_z','tri_z'];terms4=terms3+['agl_z:tpi_z']
 rows=[];results={};fits={}
 def one(name,X,terms,mask=None):
  mask=np.ones(len(m),dtype=bool) if mask is None else np.asarray(mask,dtype=bool)
  if mask.sum()<max(30,5*len(terms)):raise ValueError(f'Too few complete strata for {name}')
  r=fit(X[mask],bats[mask]);fits[name]=r
  rows.extend(coefficient_rows(r,terms,name))
  results[name]={k:v for k,v in r.items() if k not in ['beta','cov_model','cov_cluster']}
  np.savez_compressed(out/(name+'_fit.npz'),beta=r['beta'],cov_model=r['cov_model'],cov_cluster=r['cov_cluster'],terms=np.asarray(terms),included_step_ids=m.loc[mask,'step_id'].to_numpy())
  print(name,'n=',r['n_steps'],'beta=',np.round(r['beta'],6),flush=True)
  return r
 base=one('M4_main_effects',X3,terms3);full=one('M5_interaction',X4,terms4)
 loo=[]
 for ind in sorted(m.ind.unique()):
  r=one(f'LOO_without_HQ{ind}',X4,terms4,bats!=ind)
  loo.append({'test':f'Without HQ{ind}',**coefficient_rows(r,terms4,'LOO')[-1]})
 centered=m.start_agl-m.groupby('ind').start_agl.transform('mean')
 within_sd=float(np.std(np.repeat(centered.to_numpy(),41),ddof=1))
 within_z=centered.to_numpy()/within_sd
 Xw=X4.copy();Xw[:,:,3]=within_z[:,None]*X3[:,:,0]
 within=one('within_bat_AGL',Xw,terms4)
 for name,mask in [('nonnegative_start_AGL',m.start_agl>=0),('valid_heights_both',m.start_altitude_valid&m.end_altitude_valid),('dt_le_2p5',m.dt_min<=2.5),('dt_gt_2p5',m.dt_min>2.5)]:one(name,X4,terms4,mask)
 coeff=pd.DataFrame(rows);coeff.to_csv(out/'all_model_coefficients.csv',index=False)
 pd.DataFrame(coefficient_rows(base,terms3,'M4')).to_csv(out/'Fig2B_coefficients.csv',index=False)
 dd=[{'test':'Full model',**coefficient_rows(full,terms4,'M5')[-1]}]+loo+[{'test':'Within-bat AGL',**coefficient_rows(within,terms4,'centered')[-1]}]
 pd.DataFrame(dd).to_csv(out/'Fig2D_sensitivity.csv',index=False)
 hs=np.arange(0,301,5);z=(hs-scaling['start_agl']['mean'])/scaling['start_agl']['sd']
 contrasts=np.zeros((len(hs),4));contrasts[:,0]=1;contrasts[:,3]=z
 beta=contrasts@full['beta'];se=np.sqrt(np.einsum('np,pq,nq->n',contrasts,full['cov_model'],contrasts));sc=np.sqrt(np.maximum(0,np.einsum('np,pq,nq->n',contrasts,full['cov_cluster'],contrasts)))
 q=t.ppf(.975,full['n_clusters']-1)
 pd.DataFrame({'agl_m':hs,'cond_slope':beta,'se':se,'ci_lo':beta-norm.ppf(.975)*se,'ci_hi':beta+norm.ppf(.975)*se,'cluster_se':sc,'cluster_ci_lo':beta-q*sc,'cluster_ci_hi':beta+q*sc}).to_csv(out/'Fig2C_conditional_slope.csv',index=False)
 m[['step_id','ind','start_agl']].to_csv(out/'Fig2C_observed_heights.csv',index=False)
 old=pd.read_csv(ROOT/'legacy/fig2B_coefficients.csv')
 comparison=pd.DataFrame({'term':terms3,'legacy_beta':old.beta.to_numpy(),'refit_beta':base['beta'],'difference':base['beta']-old.beta.to_numpy()})
 comparison.to_csv(out/'legacy_coefficient_comparison.csv',index=False)
 scale={'pooled_long_ddof':1,'predictors':scaling,'within_individual_AGL_sd':within_sd}
 (out/'scaling.json').write_text(json.dumps(scale,indent=2))
 (out/'fit_diagnostics.json').write_text(json.dumps(results,indent=2))
 (out/'run_manifest.json').write_text(json.dumps({'candidate_sha256':hashlib.sha256(candidate_path.read_bytes()).hexdigest(),'master_sha256':hashlib.sha256((ROOT/'input/master_steps.csv').read_bytes()).hexdigest(),'candidate_rows':len(c),'n_steps':len(m),'standardization':'explicit pooled-long ddof=1 reconstruction; not claimed to be documented original setting','inference_warning':'cluster intervals use seven bats; small-cluster uncertainty remains','all_fits_converged':all(r['converged'] for r in results.values())},indent=2))
 audit_path=ROOT/'results/master_audit.json'
 audit=json.loads(audit_path.read_text());audit.update(full_candidates_supplied=True,main_models_refitted=True);audit_path.write_text(json.dumps(audit,indent=2))
 return out

if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--candidates',type=Path,required=True);a=p.parse_args()
 try:run(a.candidates)
 except (ValueError,FileNotFoundError) as e:sys.exit('Cannot refit: '+str(e))
